"""Текст конфигурации OpenTofu для тестов, которые разбирают её регулярками.

Конфигурацию можно резать по файлам (`infra/*.tf`), поэтому тесты читают её
целиком, а не `infra/main.tf`: перенос ресурса в соседний файл не должен их
ронять. Файлы идут в порядке сортировки имён и склеиваются через перевод строки,
чтобы `^\\}` в конце ресурса не слипался с началом следующего файла.
"""

from pathlib import Path

INFRA_DIR = Path("infra")


def read_infra_text() -> str:
    """Все `infra/*.tf`, склеенные в один текст."""
    return "\n".join(path.read_text() for path in sorted(INFRA_DIR.glob("*.tf")))
