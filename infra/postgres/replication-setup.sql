-- Роль для горячей реплики. Выполняется одноразовым контейнером
-- dmc268-replication-setup и обязан быть идемпотентным: init-скрипты образа
-- отрабатывают только на пустом томе, а том основной базы заведён задолго до
-- реплики. Контейнер пересоздаётся при смене пароля или этого SQL, а также
-- вместе с контейнером или томом основной базы.
--
-- Это не схема приложения (её меняет только Alembic), а объект кластера: роль
-- живёт вне базы dmc268 и миграциям не принадлежит.
--
-- Слот репликации заводит сама реплика (`pg_basebackup --create-slot`) при
-- каждой пересборке — так потерянный или удалённый слот пересоздаётся без
-- ручных шагов.
--
-- Пароль берётся из окружения (`\getenv`), а не аргументом psql: аргументы
-- видны в `ps` на хосте.

\set ON_ERROR_STOP on
\getenv replication_password REPLICATION_PASSWORD

SELECT 'CREATE ROLE replicator'
WHERE NOT EXISTS (SELECT FROM pg_roles WHERE rolname = 'replicator')
\gexec

-- Пароль переустанавливается каждый раз: смена секрета доходит до базы обычным
-- деплоем, а реплика при пересоздании перепишет свой passfile.
ALTER ROLE replicator WITH LOGIN REPLICATION NOSUPERUSER PASSWORD :'replication_password';
