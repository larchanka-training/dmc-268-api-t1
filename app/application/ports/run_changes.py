"""Сигнал «прогоны изменились» для общего потока событий.

Статус прогона пишет воркер, а поток живёт в API: общего у них только база.
Порт говорит лишь о том, что какие-то прогоны изменились после прошлого
ожидания, — что именно, поток дочитывает из базы своим курсором. Адаптер —
PostgreSQL `LISTEN` (`app/infrastructure/db/run_changes.py`).

Источник может оборваться — тогда уведомления между обрывом и переподключением
потеряны, и подписка сообщает об этом `RunChangesLost`: поток закрывается,
клиент переподключается и перезапрашивает снимок.
"""

from typing import Protocol


class RunChangesLost(Exception):
    """Источник изменений недоступен или оборвался: уведомления могли потеряться."""


class RunChangeSubscription(Protocol):
    async def wait(self, timeout: float) -> bool:
        """`True` — прогоны менялись с прошлого вызова, `False` — истёк `timeout`.

        Несколько изменений между вызовами — один `True`. Источник оборвался —
        `RunChangesLost`.
        """
        ...

    def close(self) -> None:
        """Отписаться; повторный вызов ничего не делает."""
        ...


class RunChanges(Protocol):
    async def subscribe(self) -> RunChangeSubscription:
        """Подписка на изменения с этого момента; источник недоступен — `RunChangesLost`."""
        ...
