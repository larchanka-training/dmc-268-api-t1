"""Порт best-effort кэша ключ → строка с TTL (§4.3 `docs/SYSTEM_DESIGN.md`).

Промах — не ошибка, а штатный исход: вызывающий всегда умеет получить
значение заново. Записи не инвалидируются — только вытесняются по TTL или
перезаписываются: ключ правил строится по неизменяемым данным (sha коммита), а
изменяемые данные (видимость репозиториев) живут коротко, и тот, кто знает, что
они изменились, пишет свежее значение поверх. Первый адаптер — словарь в
памяти процесса; Redis — когда кэш должен быть общим для реплик.
Значение — строка: её одинаково хранят и словарь, и Redis.
"""

from typing import Protocol


class CacheStore(Protocol):
    def get(self, key: str) -> str | None:
        """Значение по ключу или `None` — промах, истёкший TTL, вытеснение."""
        ...

    def set(self, key: str, value: str, ttl_seconds: int) -> None:
        """Сохранить значение; сбой хранилища не должен ломать вызывающего."""
        ...
