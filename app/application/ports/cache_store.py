"""Хранилище-кэш для транзиентных тяжёлых данных.

Первый клиент — приём вебхука: скачанный дифф кладётся в кэш, чтобы воркер
взял его оттуда, а не тянул третий раз у VCS (`SYSTEM_DESIGN.md` §4.3).
Семантика сознательно минимальна: положить, прочитать, вытеснить по TTL.
Нет атомарности, инкрементов и публикации-подписки — они появятся вместе с
клиентом, которому нужны (идемпотентность HTTP-слоя, rate limit).
"""

from typing import Protocol


class CacheStore(Protocol):
    def get(self, key: str) -> str | None:
        """Значение по ключу или `None`, если ключа нет или он вытеснен."""
        ...

    def put(self, key: str, value: str, *, ttl_seconds: int) -> None:
        """Положить значение; через `ttl_seconds` ключ считается отсутствующим."""
        ...
