"""Недоверенные данные в контексте модели: обезвредить и отделить.

Код, дифф, сигнатуры и проверки правил приходят из репозитория, который
контролирует автор PR, — в них может стоять «игнорируй предыдущие
инструкции». Фильтр по фразам проигрывает перефразированию, поэтому защита
структурная (модель угроз в `docs/BACKEND_ARCHITECTURE.md`):

- каждый такой текст лежит внутри блока, граница которого — хэш самого
  текста: чтобы закрыть блок досрочно, автор должен вписать в код строку с
  хэшем этого же кода, что вычислительно недостижимо;
- управляющие, bidi- и zero-width-символы заменяются видимой записью кодовой
  точки: модель видит Trojan Source, а не читает текст в порядке, который
  подсунул автор.

Граница детерминирована — чистая функция без случайности, тест сверяет
точное значение. Пути файлов в разметку не попадают: они лежат отдельными
полями пакета, где их экранирует JSON.
"""

import hashlib
import unicodedata

# Видимые и безопасные: перевод строки и табуляция — часть кода.
_KEPT_CONTROLS = frozenset({"\n", "\t"})
# Cc — управляющие, Cf — форматирующие (bidi U+202A–202E, U+2066–2069,
# zero-width U+200B–200D, U+FEFF), Zl/Zp — разделители строк и абзацев,
# которые модель может прочитать как перевод строки, а ревьюер в diff-viewer
# не увидит.
_HIDDEN_CATEGORIES = frozenset({"Cc", "Cf", "Zl", "Zp"})

_BOUNDARY_HEX = 12


def sanitize(text: str) -> str:
    """Заменить невидимые и управляющие символы записью `<U+XXXX>`."""
    return "".join(
        char
        if char in _KEPT_CONTROLS or unicodedata.category(char) not in _HIDDEN_CATEGORIES
        else f"<U+{ord(char):04X}>"
        for char in text
    )


def boundary(text: str) -> str:
    """Граница блока — префикс sha256 уже обезвреженного текста."""
    return hashlib.sha256(text.encode("utf-8")).hexdigest()[:_BOUNDARY_HEX]


def fence(kind: str, text: str) -> str:
    """Обезвредить текст и поместить в блок недоверенных данных.

    `kind` задаёт наш код (`diff`, `signature`, `import`, `rule_check`), а
    не репозиторий, поэтому в разметку попадает как есть.
    """
    clean = sanitize(text)
    tag = boundary(clean)
    return f"<<<untrusted kind={kind} id={tag}>>>\n{clean}\n<<<end id={tag}>>>"
