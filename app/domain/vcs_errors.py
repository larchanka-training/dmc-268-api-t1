"""Общая шапка сбоев VCS.

Живёт в домене, а не в порту и не в адаптере: слой приложения ловит её,
не завися от инфраструктуры, а адаптеры наследуют от неё уточняющие
исключения. Ни порт, ни адаптер не владеют базовым классом — иначе у
инфраструктуры появляется compile-time зависимость от слоя приложения
или у приложения — от вендорского адаптера.

`code` — машиночитаемый код сбоя из каталога ошибок прогона (§8
PIPELINE_SPEC.md); наследник адаптера уточняет его, слой приложения читает
атрибут, не зная наследника.
"""

from typing import ClassVar


class VcsError(RuntimeError):
    """VCS API ответил ошибкой или оказался недоступен."""

    code: ClassVar[str] = "SCM_UNAVAILABLE"


class VcsTransientError(VcsError):
    """Сбой, который пройдёт сам: сеть, лимит запросов, 5xx провайдера.

    Слою приложения нужен там, где на временный сбой надо остановиться, а не
    продолжать запросы, — проход повтора доставок вебхука (#149): вторичные
    лимиты GitHub считаются на токен, и долбить API дальше нельзя.
    """


class VcsNotFoundError(VcsError):
    """Провайдер ответил 404. Для диффа и метаданных — сбой, для `fetch_file`
    — штатный исход «файла на коммите нет», который адаптер переводит в
    `None`.

    Код — `PR_NOT_FOUND`: 404 на `compare` GitHub отдаёт одним телом и на
    неизвестный коммит (force-push убрал `head_sha`), и на репозиторий,
    которого нет или к которому у установки App больше нет доступа. Отличить
    `REPOSITORY_NOT_FOUND` можно только лишним запросом к репозиторию;
    дифф прогона ищется по коммитам PR, поэтому выбран код PR.
    """

    code: ClassVar[str] = "PR_NOT_FOUND"


class VcsFileTooLargeError(VcsError):
    """Файл или дифф больше лимита вызывающего: адаптер оборвал загрузку, не дочитав.

    Не сбой VCS, а исход лимита — вызывающий ловит его раньше `VcsError`
    (правила — статус `too_large`, AST — пропуск файла, дифф прогона —
    `DiffTooLargeError`).
    """


class DiffTooLargeError(VcsFileTooLargeError):
    """Дифф прогона больше `diff_max_bytes`: ревью не выполняется.

    Код свой, а не `SCM_UNAVAILABLE`: VCS ответила исправно, и повтор не
    поможет — как `PROMPT_TOO_LARGE` у модели. Прогон уходит в `failed`, шаг
    `fetching_diff` — с этим кодом.
    """

    code: ClassVar[str] = "DIFF_TOO_LARGE"
