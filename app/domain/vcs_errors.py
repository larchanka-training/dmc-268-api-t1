"""Общая шапка сбоев VCS.

Живёт в домене, а не в порту и не в адаптере: слой приложения ловит её,
не завися от инфраструктуры, а адаптеры наследуют от неё уточняющие
исключения. Ни порт, ни адаптер не владеют базовым классом — иначе у
инфраструктуры появляется compile-time зависимость от слоя приложения
или у приложения — от вендорского адаптера.

`code` — машиночитаемый код сбоя из каталога ошибок прогона (§8
PIPELINE_SPEC.md); наследник адаптера уточняет его, слой приложения читает
атрибут, не зная наследника.
"""

from typing import ClassVar


class VcsError(RuntimeError):
    """VCS API ответил ошибкой или оказался недоступен."""

    code: ClassVar[str] = "SCM_UNAVAILABLE"


class VcsFileTooLargeError(VcsError):
    """Файл больше лимита вызывающего: адаптер оборвал загрузку, не дочитав.

    Не сбой VCS, а исход лимита — вызывающий ловит его раньше `VcsError`
    (правила — статус `too_large`, AST — пропуск файла).
    """
